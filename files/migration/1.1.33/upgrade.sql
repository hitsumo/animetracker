--       watched_episodes > 0 ya da durum "planlandi/secilmemis" disinda
--       bir sey.
--
--   (4) "IZLENIYOR" ONCEKI HALKA ICIN IZLENMIS SAYILMAZ. Yarim
--       birakilmis bir sezonun sonunu ele veren ozet de spoiler'dir;
--       yalnizca 'Watched' kapiyi acar.
