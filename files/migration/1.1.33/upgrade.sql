--   (3) ANIMEYE BASLAMIS KULLANICIYA KAPI KURULMAZ. Izlemekte oldugun
--       (ya da bitirdigin, erteledigin, biraktigin) bir animenin
--       konusunda senin icin spoiler yoktur - onceki sezonu atlamis
