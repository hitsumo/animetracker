-- - indexnow_ping.php'nin dort kipi (--genkey, --status, --dry-run, bos
--   kuyrukla duz kosu) gercekten calistirildi; CLI disi SAPI'de betik
--   "command line only" deyip durdu.
-- - php -l 106/106.
