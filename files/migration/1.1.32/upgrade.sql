-- Runner asagidaki yorum satirlarini temizler ve tek ifadeyi calistirir;
-- tablo zaten varsa IF NOT EXISTS (ve gelirse 1050 hatasi) yok sayilir,
-- settings.version 1.1.32'ye tasinir.
